import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL, fileURLToPath, pathToFileURL } from 'node:url';

/*
 * Writes apps/api/.env and apps/web/.env.local from a running local Supabase stack.
 *
 * `supabase start` mints a fresh anon and service-role key per project, so these files cannot be
 * committed and cannot be written once by hand — they have to be regenerated whenever the stack is
 * recreated. Doing it by script keeps the two apps pointing at the same instance and keeps the
 * service-role key out of the web environment, where any NEXT_PUBLIC_ value ships to the browser.
 *
 * Chain values are placeholders: the MVP is off-chain, but the schema still validates their shape
 * at boot, so they must parse as a URL, a positive integer and an EVM address.
 */

const repositoryRoot = new URL('../', import.meta.url);

const CHAIN_PLACEHOLDERS = Object.freeze({
  ARC_RPC_URL: 'http://127.0.0.1:8545',
  ARC_CHAIN_ID: '31337',
  USDC_ADDRESS: '0x0000000000000000000000000000000000000001',
});

/** `supabase status -o env` emits KEY="value" lines. */
export function parseSupabaseStatus(output) {
  const values = new Map();

  for (const line of output.split(/\r?\n/)) {
    const match = /^([A-Z0-9_]+)="?(.*?)"?$/.exec(line.trim());
    if (match !== null) values.set(match[1], match[2]);
  }

  return values;
}

function required(values, key) {
  const value = values.get(key);
  if (value === undefined || value === '') {
    throw new Error(`supabase status did not report ${key} — is the stack running?`);
  }
  return value;
}

function writeEnvironmentFile(relativePath, entries) {
  const body = [
    '# Generated by scripts/setup-local-env.mjs from the running local Supabase stack.',
    '# Regenerate after `supabase stop`/`supabase start` — the keys change with the project.',
    '',
    ...entries.map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n');

  const target = new URL(relativePath, repositoryRoot);
  writeFileSync(target, body, 'utf8');
  return fileURLToPath(target);
}

export function buildEnvironments(values) {
  const apiUrl = required(values, 'API_URL');
  const anonKey = required(values, 'ANON_KEY');
  const serviceRoleKey = required(values, 'SERVICE_ROLE_KEY');

  return {
    api: [
      ['NODE_ENV', 'development'],
      ['PORT', '3001'],
      ['WEB_APP_ORIGIN', 'http://localhost:3000'],
      ['SUPABASE_URL', apiUrl],
      ['SUPABASE_ANON_KEY', anonKey],
      ['SUPABASE_SERVICE_ROLE_KEY', serviceRoleKey],
      ...Object.entries(CHAIN_PLACEHOLDERS),
      ['AI_PROVIDER', 'mock'],
      ['LOG_LEVEL', 'debug'],
    ],
    // Only the anon key belongs here: NEXT_PUBLIC_ values are compiled into the client bundle.
    web: [
      ['NEXT_PUBLIC_API_BASE_URL', 'http://localhost:3001'],
      ['NEXT_PUBLIC_SUPABASE_URL', apiUrl],
      ['NEXT_PUBLIC_SUPABASE_ANON_KEY', anonKey],
      ['NEXT_PUBLIC_ARC_RPC_URL', CHAIN_PLACEHOLDERS.ARC_RPC_URL],
      ['NEXT_PUBLIC_ARC_EXPLORER_URL', 'http://127.0.0.1:4000'],
      ['NEXT_PUBLIC_ARC_CHAIN_ID', CHAIN_PLACEHOLDERS.ARC_CHAIN_ID],
      ['NEXT_PUBLIC_USDC_ADDRESS', CHAIN_PLACEHOLDERS.USDC_ADDRESS],
    ],
  };
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const output = execFileSync('pnpm', ['exec', 'supabase', 'status', '-o', 'env'], {
    cwd: fileURLToPath(repositoryRoot),
    encoding: 'utf8',
    shell: process.platform === 'win32',
  });

  const values = parseSupabaseStatus(output);
  const { api, web } = buildEnvironments(values);

  // Keys are never echoed: this runs in a shared terminal and the service-role key bypasses RLS.
  process.stdout.write(`wrote ${writeEnvironmentFile('apps/api/.env', api)}\n`);
  process.stdout.write(`wrote ${writeEnvironmentFile('apps/web/.env.local', web)}\n`);
  process.stdout.write(`SUPABASE_URL=${required(values, 'API_URL')}\n`);
  process.stdout.write(`DB_URL=${required(values, 'DB_URL')}\n`);
}
